
[ ! -d energy_ranges ] && mkdir energy_ranges

cd energy_ranges

distances="100 200 300 400 500 600 800 900 1000"

for dist in $distances
do 
	file=Z$dist.txt

	[ ! -d $dist ] && mkdir $dist

	cd $dist

	cp ../../$file .

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.005 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.004' $file > '40_50_bin_'$dist'.txt'

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.004 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.003' $file > '30_40_bin_'$dist'.txt'

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.003 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.002' $file >' 20_30_bin_'$dist'.txt'

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.002 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.001' $file > '10_20_bin_'$dist'.txt'

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.0002 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.0001' $file > '1_2_bin_'$dist'.txt'

	awk '((($4**2)+($5**2)+($6**2))/(2*105.66)) <= 0.0001 && ((($4**2)+($5**2)+($6**2))/(2*105.66)) > 0.00001' $file > '100_1_bin_'$dist'.txt'

	
	cd ..

done 